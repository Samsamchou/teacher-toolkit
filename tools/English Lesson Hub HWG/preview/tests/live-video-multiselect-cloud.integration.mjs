import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createLiveService} from '../functions/src/live-service.mjs';
import {newBlock} from '../src/live/domain.mjs';
import {parityBlock} from '../src/live/parity.mjs';
if(!/^(127\.0\.0\.1|localhost):\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST||''))throw new Error('Local emulator required');
const require=createRequire(new URL('../functions/index.cjs',import.meta.url));
const {initializeApp,deleteApp}=require('firebase-admin/app');
const {getFirestore}=require('firebase-admin/firestore');
test('Firestore persists teacher video commands and per-option multiselect report',async()=>{
 const app=initializeApp({projectId:'demo-lesson-hub'},'video-'+Date.now()),db=getFirestore(app);
 const teacher='teacher-'+crypto.randomUUID(),student='student-'+crypto.randomUUID();
 const service=createLiveService({db,now:()=>Date.now(),requireTeacher:async r=>{if(r.auth.uid!==teacher)throw new Error('teacher only');}});
 const call=(uid,action,code,payload={})=>service({auth:{uid,token:{firebase:{sign_in_provider:'anonymous'}}},data:{action,code,payload}});
 try{
  const slide={...parityBlock(newBlock('slide')),embed:'https://youtu.be/M7lc1UVf-VE'},multi={...parityBlock(newBlock('multiselect')),points:6};
  const deck={id:crypto.randomUUID(),title:'Video + multi QA',blocks:[slide,multi]};
  const saved=await call(teacher,'saveDeck',null,{deck,expectedVersion:0});
  let r=await call(teacher,'create',null,{deck:saved.deck});const code=r.code;
  await call(student,'join',code,{studentId:'50101'});
  r=await call(teacher,'control',code,{action:'start',revision:r.revision});
  r=await call(teacher,'control',code,{action:'video',revision:r.revision,blockId:slide.id,command:'play',position:12});
  assert.equal((await call(student,'snapshot',code)).video.position,12);
  await assert.rejects(call(student,'control',code,{action:'video',revision:r.revision,blockId:slide.id,command:'pause',position:12}));
  r=await call(teacher,'control',code,{action:'move',revision:r.revision,index:1});assert.equal(r.video,null);
  r=await call(teacher,'control',code,{action:'open',revision:r.revision});
  const s=await call(student,'snapshot',code);assert.equal(s.block.requiredSelections,3);assert.equal(s.block.answer,undefined);
  const input={attemptId:crypto.randomUUID(),blockId:multi.id,revision:r.revision,answer:[1,2,0]};
  await assert.rejects(call(student,'submit',code,{...input,answer:[]}));
  const submitted=await call(student,'submit',code,input);
  assert.deepEqual(submitted.feedback,{attemptId:input.attemptId,outcome:'partial',mastery:true});
  assert.equal(submitted.block.answer,undefined);
  assert.equal(submitted.responses[0].grade.score,undefined);
  assert.deepEqual((await call(student,'submit',code,input)).feedback,submitted.feedback);
  const row=(await call(teacher,'report',code)).report[0];assert.equal(row.score,2);assert.equal(row.submitted,1);assert.match(JSON.stringify(row),/multiselect-1/);
  const result=(await call(teacher,'snapshot',code)).responses[0];assert.equal(result.grade.details.length,4);
  const privateSnapshot=await call(student,'snapshot',code);
  assert.equal(privateSnapshot.responses[0].grade.details,undefined);
  assert.equal(privateSnapshot.feedback,undefined);
  const mediaId='cloud-'+crypto.randomUUID();
  await db.collection('liveMediaV2').doc(mediaId).set({ownerUid:teacher,status:'ready',kind:'video'});
  const uploaded={...parityBlock(newBlock('slide')),syncVideoId:mediaId,media:[{id:mediaId,kind:'video',name:'synthetic.mp4'}]};
  const uploadDeck={id:crypto.randomUUID(),title:'Uploaded sync QA',blocks:[uploaded]};
  const stored=await call(teacher,'saveDeck',null,{deck:uploadDeck,expectedVersion:0});
  let u=await call(teacher,'create',null,{deck:stored.deck});await call(student,'join',u.code,{studentId:'50101'});
  u=await call(teacher,'control',u.code,{action:'start',revision:u.revision});
  u=await call(teacher,'control',u.code,{action:'video',revision:u.revision,blockId:uploaded.id,assetId:mediaId,command:'play',position:5});
  assert.equal((await call(student,'snapshot',u.code)).video.assetId,mediaId);
  await assert.rejects(call(student,'control',u.code,{action:'video',revision:u.revision,blockId:uploaded.id,assetId:mediaId,command:'pause',position:6}));
  u=await call(teacher,'control',u.code,{action:'video',revision:u.revision,blockId:uploaded.id,assetId:mediaId,command:'pause',position:6});
  assert.equal((await call(student,'snapshot',u.code)).video.playing,false);
  await assert.rejects(call(teacher,'create',null,{deck:{...uploadDeck,id:crypto.randomUUID(),blocks:[{...uploaded,media:[{id:'cloud-unowned',kind:'video'}],syncVideoId:'cloud-unowned'}]}}));
 }finally{await deleteApp(app);}
});
