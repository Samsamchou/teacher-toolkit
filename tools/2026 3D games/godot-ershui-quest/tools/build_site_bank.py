"""產生網站用的題庫 data.js（給網頁外框計分、教師後台顯示題目用）。

用法：python -I tools/build_site_bank.py
輸出：escape room HWG5-U01-U02/site/public/ershui-3d-quest/data.js
- seq 依「地點順序 → 地點內題目順序」編成 1–51。
- battles = 13 個地點（教師後台的「戰鬥」欄＝通關地點數；最後一個是水心之初大草原魔王）。
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
OUT = Path(r"G:\我的雲端硬碟\teacher-toolkit\tools\escape room HWG5-U01-U02\site\public\ershui-3d-quest\data.js")

LOCS = [
    ("station", "二水火車站", "train station"), ("inn", "二八水驛站", "restaurant"),
    ("seven", "便利商店", "convenience store"), ("school", "二水國小", "school"),
    ("teatop", "飲料店", "tea shop"), ("market", "二水超市", "supermarket"),
    ("post", "二水郵局", "post office"), ("bookstore", "書店", "bookstore"),
    ("pxmart", "超市", "supermarket"), ("library", "二水鄉立圖書館", "library"),
    ("farm", "八堡圳農情館", "coffee shop"), ("park", "二八水水公園", "park"),
    ("lawn", "水心之初大草原", "park"),
]
BOSS = {"park", "lawn"}


def main() -> None:
    q = json.loads((HERE / "data" / "questions.json").read_text(encoding="utf-8"))
    plan = json.loads((HERE / "data" / "quiz_plan.json").read_text(encoding="utf-8"))["locations"]
    by_id = {i["id"]: i for i in q["items"]}
    items = []
    for loc, _zh, _en in LOCS:
        for qid in plan[loc]:
            it = by_id[qid]
            row = {"seq": len(items) + 1, "id": qid, "bankId": qid, "type": it["type"], "location": loc,
                   "answerText": it["correctEn"]}
            if it["type"] == "spell":
                row["spell"] = {"answer": it["spell"]["answer"]}
            elif it["type"] == "drag":
                row["lines"] = it["lines"]
                row["blanks"] = it["blanks"]
            else:
                row["transcript"] = it.get("transcript")
            items.append(row)
    assert len(items) == 51, len(items)
    bank = {
        "mission": "ershui-3d-quest",
        "unit": "二水 3D 英語闖關 HWG5 R1",
        "title": "Ershui 3D English Quest",
        "items": items,
        "battles": [{"id": loc, "arena": zh, "word": en, "boss": loc in BOSS} for loc, zh, en in LOCS],
        "rewardIcons": {},
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// Generated by godot-ershui-quest/tools/build_site_bank.py — do not edit by hand.\n"
                   "export const BANK = " + json.dumps(bank, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print("wrote", OUT, len(items), "items")


if __name__ == "__main__":
    main()
