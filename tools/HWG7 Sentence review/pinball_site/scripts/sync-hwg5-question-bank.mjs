#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import {
  findPrivatePublicKeys,
  projectHwg5PublicBank,
} from "./lib/hwg5-bank-projection.mjs";
import { verifyHwg5Media } from "./verify-hwg5-media.mjs";

const privateBankUrl = new URL("../data/hwg5-sentence-review.json", import.meta.url);
const publicBankUrl = new URL("../data/hwg5-sentence-review.js", import.meta.url);
const bank = JSON.parse(await readFile(privateBankUrl, "utf8"));
const mediaVerification = await verifyHwg5Media();
const publicQuestions = projectHwg5PublicBank(bank);
const leaks = findPrivatePublicKeys(publicQuestions);
if (leaks.length) throw new Error(`Private HWG5 scoring fields leaked into browser data: ${leaks.join(", ")}`);

const payload = JSON.stringify(publicQuestions);
const hash = createHash("sha256").update(payload).digest("hex");
const output = [
  "/* AUTO-GENERATED by scripts/sync-hwg5-question-bank.mjs.",
  " * Full answers and scoring slots remain in data/hwg5-sentence-review.json for backend sync only.",
  ` * public-questions-sha256: ${hash}`,
  " */",
  `window.HWG5_SPEECH_QUESTIONS = ${JSON.stringify(publicQuestions, null, 2)};`,
  "window.HWG5_SENTENCE_REVIEW_BANK = window.HWG5_SPEECH_QUESTIONS;",
  "",
].join("\n");
await writeFile(publicBankUrl, output, "utf8");

console.log(JSON.stringify({
  unitId: bank.mode?.unitId,
  questionBankVersion: bank.mode?.questionBankVersion,
  questionCount: publicQuestions.length,
  privateFieldLeakCount: leaks.length,
  globals: ["HWG5_SPEECH_QUESTIONS", "HWG5_SENTENCE_REVIEW_BANK"],
  mediaVerification: {
    imageCount: mediaVerification.imageCount,
    ttsCount: mediaVerification.ttsCount,
    ttsBytes: mediaVerification.ttsBytes,
    ttsDurationSeconds: mediaVerification.ttsDurationSeconds,
  },
  hash,
}, null, 2));
