# 可以改用程式動畫、省下新圖的候選（給老師選）
OPTIONAL = {'N06': '可改成在 S16 水圳圖上用程式疊稻穗和米袋',
            'N08': '可改成沿用 S24b 綠色隧道騎車圖，加上量尺',
            'N15': '可改成把 N14 廠房圖調暗、用程式畫上關起的大門'}
# 依實景照片描述的新圖（要先上網找最新照片，避免畫成舊樣子）
REAL = ['N04', 'N11', 'N14']

SEC = {'open': '開場', 'ershui': '二水', 'yuanquan': '源泉', 'jiji': '集集', 'shuili': '水里', 'checheng': '車埕', 'ending': '結尾'}

def main():
    units = TL['units']; assert len(units) == len(S) == 61
    rows = []
    for n, u in enumerate(units, 1):
        src, img, desc = S[n]
        rows.append({'unit': n, 'sec': u['sec'], 'who': u['name'], 't0': round(u['t0'], 2), 'dur': round(u['t1'] - u['t0'], 2),
                     'text': u['text'], 'source': src, 'image': img, 'shot': desc})
    news = [r for r in rows if r['source'] == '新']
    (HERE / 'storyboard-v2.json').write_text(json.dumps({'dur': TL['dur'], 'rows': rows, 'optional_code_instead': OPTIONAL, 'real_place_refs': REAL},
                                                         ensure_ascii=False, indent=1), encoding='utf-8')
    md = ['# 集集線延長版：逐句分鏡表（v2，約 5:08）', '',
          f'共 {len(rows)} 個句意單位：沿用 v1 圖 {sum(r["source"]=="v1" for r in rows)}、程式動畫 {sum(r["source"]=="程式" for r in rows)}、**新生圖 {len(news)} 張**。標【新】的是延長版新增的畫面。', '']
    cur = None
    for r in rows:
        if r['sec'] != cur:
            cur = r['sec']; md += ['', f'## {SEC[cur]}', '', '| # | 時間 | 台詞 | 畫面來源 | 畫面與動畫 |', '|---|---|---|---|---|']
        mark = f'**新圖 {r["image"]}**' if r['source'] == '新' else (r['image'] if r['source'] == 'v1' else f'程式（{r["image"]}）')
        m, s = divmod(r['t0'], 60)
        md.append(f'| {r["unit"]} | {int(m)}:{s:04.1f}（{r["dur"]} 秒） | {r["who"]}：{r["text"]} | {mark} | {r["shot"]} |')
    md += ['', '## 新生圖清單', '', '| 代號 | 句意 # | 畫面 | 備註 |', '|---|---|---|---|']
    for r in news:
        note = []
        if r['image'] in REAL: note.append('先找最新實景照片')
        if r['image'] in OPTIONAL: note.append('可省：' + OPTIONAL[r['image']])
        if '小晨' in r['shot'] or '小哲' in r['shot']: note.append('用角色設定圖當參考')
        md.append(f'| {r["image"]} | {r["unit"]} | {r["shot"].replace("【新】", "")} | {"；".join(note)} |')
    (HERE / 'storyboard-v2.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
    print('rows', len(rows), 'new', len(news))

if __name__ == '__main__':
    main()
